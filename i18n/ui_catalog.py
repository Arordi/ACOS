def get_ui_catalog(language: str) -> dict[str, Any]:
    """
    Return the UI catalog for a requested language.

    Unknown languages fall back to English.
    """
    language = (language or "en").strip().lower()

    if language in UI_CATALOG:
        return deepcopy(UI_CATALOG[language])

    base_language = language.split("-")[0]

    if base_language in UI_CATALOG:
        return deepcopy(UI_CATALOG[base_language])

    return deepcopy(UI_CATALOG["en"])


def get_supported_ui_languages() -> list[str]:
    return list(UI_CATALOG.keys())


def get_translation(language: str, key: str, default: str | None = None) -> str:
    catalog = get_ui_catalog(language)
    translations = catalog.get("translations", {})

    if key in translations:
        return str(translations[key])

    if default is not None:
        return default

    return key
